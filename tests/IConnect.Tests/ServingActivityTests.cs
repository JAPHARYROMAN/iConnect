    [Fact]
    public async Task Serving_activity_runs_after_permission_and_operation_locks_and_logger_faults_preserve_the_result()
    {
        await using var f = new Fixture(StoragePermission.ReadOnly); await f.Initialize();
        var events = new ConcurrentQueue<WindowsActivityEvent>(); var reentered = 0; Exception? callbackError = null; FileStatus? nestedStatus = null;
        f.Grants.Activity = value =>
        {
            events.Enqueue(value);
            if (Interlocked.Increment(ref reentered) == 1)
                try { nestedStatus = f.Raw(new() { Operation = FileOperation.ListRoots }).WaitAsync(TimeSpan.FromSeconds(5)).GetAwaiter().GetResult().Status; }
                catch (Exception error) { callbackError = error; }
        };
        Assert.Equal(FileStatus.Ok, (await f.Raw(new() { Operation = FileOperation.GetMetadata, NodeId = f.Parent })).Status);
        var descriptor = Fixture.Descriptor("NEVER-RECORD-FILENAME.txt", "generated bytes"u8.ToArray());
        var denied = await f.Raw(new() { Operation = FileOperation.PrepareUpload, DestinationId = f.Parent, MutationEpoch = f.Epoch, TransferId = descriptor.Id, Upload = descriptor });
        Assert.Equal(FileStatus.AccessDenied, denied.Status);
        Assert.Contains(events, x => x.Outcome == WindowsActivityOutcome.Accepted && x.Operation == FileOperation.GetMetadata);
        Assert.Contains(events, x => x.Outcome == WindowsActivityOutcome.Refused && x.Operation == FileOperation.PrepareUpload);
        Assert.True(reentered >= 3); Assert.Null(callbackError); Assert.Equal(FileStatus.Ok, nestedStatus);
        f.Grants.Activity = _ => throw new IOException("generated private logger error");
        Assert.Equal(FileStatus.Ok, (await f.Raw(new() { Operation = FileOperation.ListRoots })).Status);
        Assert.Empty(Directory.GetFileSystemEntries(f.Destination)); Assert.Single(f.Grants.All);
    }
    [Fact]
    public async Task Successful_range_status_polling_is_quiet_but_refusals_and_cancellation_remain_observable()
    {
        await using var f = new Fixture(); await f.Initialize(); var events = new ConcurrentQueue<WindowsActivityEvent>(); f.Grants.Activity = events.Enqueue;
        var row = await f.Begin(Fixture.Descriptor("generated-small.txt", "generated bytes"u8.ToArray()));
        events.Clear();
        await f.Call(new() { Operation = FileOperation.UploadStatus, TransferId = row.Id, MutationEpoch = f.Epoch }); Assert.Empty(events);
        var denied = await f.Raw(new() { Operation = FileOperation.UploadStatus, TransferId = row.Id, MutationEpoch = f.Epoch }, new string('b', 64));
        Assert.Equal(FileStatus.NotFound, denied.Status); Assert.Contains(events, x => x.Outcome == WindowsActivityOutcome.Failed);
        var refused = await f.Raw(new() { Operation = FileOperation.ReadRange, NodeId = f.Parent, Length = 1 }, new string('b', 64));
        Assert.Equal(FileStatus.AccessDenied, refused.Status); Assert.Contains(events, x => x.Outcome == WindowsActivityOutcome.Refused);
        using var canceled = new CancellationTokenSource(); canceled.Cancel();
        await Assert.ThrowsAnyAsync<OperationCanceledException>(() => f.Service.ExecuteAsync(f.Peer, new() { RequestId = ProtocolRules.NewToken(), Operation = FileOperation.ListRoots }, canceled.Token));
        Assert.Contains(events, x => x.Outcome == WindowsActivityOutcome.Canceled);
        events.Clear(); await f.Service.ExecuteAsync(f.Peer, new() { RequestId = "iconnect://NEVER-RECORD-INVALID-REQUEST", Operation = FileOperation.ListRoots }, default); Assert.Empty(events);
    }
    [Fact]
    public async Task Actual_verified_incoming_publication_is_recorded_after_its_commit_and_survives_a_throwing_logger()
    {
        await using var f = new Fixture(); await f.Initialize(); var store = new LocalActivityStore(f.Profile);
        await using var writer = new DesktopActivityWriter(store, () => { }); f.Grants.Activity = writer.Record;
        var bytes = "generated private received bytes"u8.ToArray(); var row = await f.Begin(Fixture.Descriptor("NEVER-RECORD-FILENAME.txt", bytes)); await f.Write(row, bytes);
        await writer.Flush(); Assert.DoesNotContain(store.All, x => x.Description.StartsWith("Incoming file publication · completed"));
        var completed = await f.Finish(row); Assert.Equal(UploadPhase.UploadCompleted, completed.Phase); await writer.Flush();
        Assert.Contains(store.All, x => x.Description == $"Incoming file publication · completed · {bytes.Length} bytes");
        Assert.Equal(bytes, File.ReadAllBytes(Path.Combine(f.Destination, completed.FinalName)));
        var json = File.ReadAllText(Path.Combine(f.Profile, "activity.json")); Assert.DoesNotContain("NEVER-RECORD-FILENAME", json); Assert.DoesNotContain(f.Destination, string.Join('\n', store.All.Select(x => x.Description))); Assert.DoesNotContain(Convert.ToHexStringLower(System.Security.Cryptography.SHA256.HashData(bytes)), json);
        f.Grants.Activity = _ => throw new IOException("generated private logger error");
        var next = await f.Begin(Fixture.Descriptor("second-generated-copy.txt", bytes)); await f.Write(next, bytes);
        Assert.Equal(UploadPhase.UploadCompleted, (await f.Finish(next)).Phase); Assert.Equal(bytes, File.ReadAllBytes(Path.Combine(f.Destination, "second-generated-copy.txt")));
    }
}

public sealed partial class DesktopModelTests
{
    [Fact]
    public async Task Serving_writer_is_bounded_groups_fixed_events_and_orders_clear_off_and_reopen()
    {
        var store = new LocalActivityStore(state); var notifications = 0; var writer = new DesktopActivityWriter(store, () => Interlocked.Increment(ref notifications));
        try
        {
            for (var index = 0; index < 10_000; index++) writer.Record(new(WindowsActivityKind.FileRequest, WindowsActivityOutcome.Accepted, "iconnect://NEVER-RECORD-PEER-SECRET", Operation: FileOperation.GetMetadata));
            await writer.Flush(); Assert.True(writer.Dropped > 0); Assert.InRange(notifications, 1, 100); Assert.InRange(store.All.Count, 1, 500); Assert.All(store.All, x => Assert.Null(x.PeerId));
            Assert.Contains(store.All, x => x.Description.Contains("events")); Assert.DoesNotContain("NEVER-RECORD", File.ReadAllText(Path.Combine(state, "activity.json")));
            await writer.Clear(); Assert.Empty(store.All);
            writer.Record(new(WindowsActivityKind.FileRequest, WindowsActivityOutcome.Accepted)); await writer.Configure(0); Assert.Empty(store.All);
            writer.Record(new(WindowsActivityKind.IncomingCopy, WindowsActivityOutcome.Completed, Bytes: 5)); await writer.Flush(); Assert.Empty(store.All);
        }
        finally { await writer.DisposeAsync(); }
        Assert.Equal(0, new LocalActivityStore(state).Days);
    }
    [Fact]
    public async Task Serving_writer_reports_journal_failure_preserves_changed_bytes_and_retries_only_after_reset()
    {
        var store = new LocalActivityStore(state); await using var writer = new DesktopActivityWriter(store, () => { });
        var keep = Path.Combine(directory, "owner.txt"); File.WriteAllText(keep, "generated owner bytes");
        writer.Record(new(WindowsActivityKind.FileRequest, WindowsActivityOutcome.Accepted)); await writer.Flush();
        var path = Path.Combine(state, "activity.json"); File.AppendAllText(path, " generated external change");
        writer.Record(new(WindowsActivityKind.IncomingCopy, WindowsActivityOutcome.Completed, Bytes: 4)); await Assert.ThrowsAsync<IOException>(() => writer.Flush());
        Assert.True(writer.Dropped > 0); Assert.NotEmpty(store.Issue); Assert.EndsWith(" generated external change", File.ReadAllText(path));
        await writer.Reset(); writer.Record(new(WindowsActivityKind.FileRequest, WindowsActivityOutcome.Accepted)); await writer.Flush();
        Assert.Empty(store.Issue); Assert.Single(store.All); Assert.Equal("generated owner bytes", File.ReadAllText(keep));
    }
    [Fact]
    public async Task Concurrent_serving_writer_close_drains_accepted_commands_and_late_controls_fail_without_hanging()
    {
        var store = new LocalActivityStore(state); var writer = new DesktopActivityWriter(store, () => { });
        for (var index = 0; index < 64; index++) writer.Record(new(WindowsActivityKind.FileRequest, WindowsActivityOutcome.Accepted));
        var controls = Enumerable.Range(0, 32).Select(_ => writer.Flush()).ToArray();
        var first = writer.DisposeAsync().AsTask(); var second = writer.DisposeAsync().AsTask(); var late = writer.Clear();
        await Task.WhenAll(controls.Append(first).Append(second)).WaitAsync(TimeSpan.FromSeconds(10));
        await Assert.ThrowsAsync<ObjectDisposedException>(() => late); Assert.NotEmpty(new LocalActivityStore(state).All);
        await Assert.ThrowsAsync<ObjectDisposedException>(() => writer.Flush()); await writer.DisposeAsync();
    }
}
